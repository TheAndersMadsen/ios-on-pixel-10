"""hk_port_config.py: the blazer kernel's drivers as XNU options (config/hakios/*.drivers in the XNU tree).

usage:
  hk_port_config.py [--xnu DIR] list                       every driver: subsystem, files, requires, gates, ladder step
  hk_port_config.py [--xnu DIR] help NAME                  one driver
  hk_port_config.py [--xnu DIR] sync                       write the configuration-independent parts into the tree:
                                                           conf/files conditions, MASTER options, bsd/dev/hakios.blazer_drivers.h
  hk_port_config.py [--xnu DIR] apply CONFIG               write config/MASTER.arm64.blazer's HAKIOS_DRIVERS line for CONFIG
  hk_port_config.py [--xnu DIR] show CONFIG                which drivers CONFIG builds and leaves out
  hk_port_config.py [--xnu DIR] check [CONFIG]             the tree agrees with config/hakios (exit 1 + problems if not)
  hk_port_config.py [--xnu DIR] bootline CONFIG --line L [--extra E]
                                                           refuse a port boot-arg that only left-out drivers read
                                                           (catalogue: hk_bootargs.py, HakiOS lift 5)

CONFIG is a file of `CONFIG_HAKIOS_<NAME>=y`, `# CONFIG_HAKIOS_<NAME> is not set` and `#include <file>` lines
(devices/blazer/configs/). A driver CONFIG does not name gets its `default` (y unless said).
XNU DIR: --xnu, else $HK_PORT_XNU, else /data/work/hk-port-build/xnu5 (hk-port-2 on hk-base-5).
"""
import argparse
import importlib.util
import os
import re
import sys

CONF_DIR = 'config/hakios'
MASTER = 'config/MASTER'
MASTER_CPU = 'config/MASTER.arm64.blazer'
HEADER = 'bsd/dev/hakios.blazer_drivers.h'
FILES = ('bsd/conf/files', 'bsd/conf/files.arm64', 'iokit/conf/files', 'iokit/conf/files.arm64',
         'osfmk/conf/files', 'osfmk/conf/files.arm64')
# Files that are this port's drivers or services: each must be named by exactly one conf line.
PORT_FILE = re.compile(r'^(bsd/dev/(blazer_|hakios\.|sweet_|tegu_|hk_btsk|hmfw_)|iokit/Kernel/arm/(Sweet|sweet_|Blazer|blazer_|tensor_)'
                       r'|iokit/Kernel/arm/hid/Sweet|osfmk/arm64/blazer_|bsd/kern/sweet_)')
CONFIGS = ('RELEASE', 'DEVELOPMENT', 'DEBUG', 'KASAN')
OPT_BEGIN = '# hakios drivers: generated by hackios tools/hk_port_config.py sync from config/hakios/*.drivers'
OPT_END = '# end of the hakios drivers'
GROUP = re.compile(r'^#  HAKIOS_DRIVERS =.*$', re.M)


class Driver:
    def __init__(self, name, sub, line):
        self.name, self.sub, self.line = name, sub, line
        self.files, self.requires, self.gates, self.help = [], [], [], []
        self.default, self.ladder = True, None

    @property
    def attr(self):
        return 'hakios_' + self.name.lower()


def xnu_dir(arg):
    return arg or os.environ.get('HK_PORT_XNU') or '/data/work/hk-port-build/xnu5'


def parse(xnu):
    """drivers {NAME: Driver}, standard [(path, opts, where)], problems."""
    drivers, standard, problems = {}, [], []
    cdir = os.path.join(xnu, CONF_DIR)
    if not os.path.isdir(cdir):
        return drivers, standard, ['%s does not exist' % CONF_DIR]
    for fn in sorted(os.listdir(cdir)):
        if not fn.endswith('.drivers'):
            continue
        sub = fn[:-len('.drivers')]
        cur = None
        for no, raw in enumerate(open(os.path.join(cdir, fn), encoding='utf-8'), 1):
            where = '%s/%s:%d' % (CONF_DIR, fn, no)
            text = raw.split('#', 1)[0].rstrip() if not raw.lstrip().startswith('help') else raw.rstrip()
            if not text.strip():
                continue
            words = text.split()
            indented = raw[0] in ' \t'
            if not indented:
                if words[0] == 'standard' and len(words) >= 2:
                    standard.append((words[1], words[2:], where))
                    cur = ('standard', None)
                elif words[0] == 'driver' and len(words) == 2 and re.match(r'^[A-Z0-9_]+$', words[1]):
                    if words[1] in drivers:
                        problems.append('%s: driver %s declared twice (first %s)' % (where, words[1], drivers[words[1]].line))
                    cur = ('driver', Driver(words[1], sub, where))
                    drivers[words[1]] = cur[1]
                else:
                    problems.append('%s: want `standard PATH` or `driver NAME`, got %r' % (where, text.strip()))
                continue
            if cur is None:
                problems.append('%s: an indented line before any block' % where)
                continue
            key, rest = words[0], words[1:]
            if key == 'help':
                if cur[0] == 'driver':
                    cur[1].help.append(' '.join(rest))
                continue
            if cur[0] != 'driver':
                problems.append('%s: `%s` only belongs to a driver' % (where, key))
                continue
            d = cur[1]
            if key == 'file' and rest:
                d.files.append((rest[0], rest[1:], where))
            elif key == 'requires':
                d.requires += rest
            elif key == 'gate':
                d.gates += rest
            elif key == 'ladder' and len(rest) == 1 and rest[0].isdigit():
                d.ladder = int(rest[0])
            elif key == 'default' and rest in (['y'], ['n']):
                d.default = rest == ['y']
            else:
                problems.append('%s: unknown or malformed %r' % (where, text.strip()))
    for d in drivers.values():
        if not d.files:
            problems.append('%s: driver %s has no file' % (d.line, d.name))
        for r in d.requires:
            if r not in drivers:
                problems.append('%s: %s requires unknown driver %s' % (d.line, d.name, r))
    return drivers, standard, problems


def read_config(path, seen=None):
    """{NAME: True/False} as the file says, following #include (relative to the file)."""
    seen = seen or set()
    path = os.path.abspath(path)
    if path in seen:
        raise SystemExit('%s: #include loop' % path)
    seen.add(path)
    out = {}
    for no, raw in enumerate(open(path, encoding='utf-8'), 1):
        line = raw.strip()
        m = re.match(r'^#include\s+(\S+)$', line)
        if m:
            out.update(read_config(os.path.join(os.path.dirname(path), m.group(1)), seen))
            continue
        m = re.match(r'^CONFIG_HAKIOS_([A-Z0-9_]+)=(y|n)$', line)
        if m:
            out[m.group(1)] = m.group(2) == 'y'
            continue
        m = re.match(r'^# CONFIG_HAKIOS_([A-Z0-9_]+) is not set$', line)
        if m:
            out[m.group(1)] = False
            continue
        if line and not line.startswith('#') and not line.startswith('CONFIG_'):
            raise SystemExit('%s:%d: not a configuration line: %r' % (path, no, line))
    return out


def resolve(drivers, config_path):
    """(set of drivers on, problems)."""
    chosen = read_config(config_path) if config_path else {}
    problems = ['%s names CONFIG_HAKIOS_%s, which no config/hakios block declares' % (config_path, n)
                for n in chosen if n not in drivers]
    on = {n for n, d in drivers.items() if chosen.get(n, d.default)}
    for n in sorted(on):
        for r in drivers[n].requires:
            if r not in on:
                problems.append('CONFIG_HAKIOS_%s requires CONFIG_HAKIOS_%s (%s)' % (n, r, drivers[n].line))
    return on, problems


# ---- the tree's files ---------------------------------------------------------------------------------------------

def read_files_lines(xnu):
    """{path: (conf file, line index, words after the path)} for every file line of the components' conf/files."""
    out = {}
    for f in FILES:
        p = os.path.join(xnu, f)
        if not os.path.isfile(p):
            continue
        for i, raw in enumerate(open(p, encoding='utf-8').read().split('\n')):
            if not raw.strip() or raw.lstrip().startswith('#'):
                continue
            words = raw.split()
            out.setdefault(words[0], (f, i, words[1:]))
    return out


def wanted_condition(opts, attr=None):
    """The words a conf/files line should carry after its path."""
    conds = list(opts) + ([attr] if attr else [])
    return ['optional'] + conds if conds else ['standard']


def expected(drivers, standard):
    want = {}
    for path, opts, where in standard:
        want[path] = (wanted_condition(opts), where)
    for d in drivers.values():
        for path, opts, where in d.files:
            want[path] = (wanted_condition(opts, d.attr), where)
    return want


def header_text(drivers):
    names = sorted(drivers, key=lambda n: (drivers[n].ladder if drivers[n].ladder is not None else 99, n))
    out = ['/* SPDX-License-Identifier: MIT',
           ' * GENERATED by hackios tools/hk_port_config.py sync from config/hakios/*.drivers: do not edit.',
           ' * Every driver of the blazer port, each present only when its XNU option HAKIOS_<NAME> is on, so the list',
           ' * is what this kernel was really compiled with (bsd/dev/hakios.blazer_drivers.c). */',
           '#ifndef HAKIOS_BLAZER_DRIVERS_H', '#define HAKIOS_BLAZER_DRIVERS_H', '']
    for n in names:
        out += ['#ifdef HAKIOS_%s' % n, '#define HKD_%s " %s"' % (n, n), '#define HKN_%s 1' % n, '#else',
                '#define HKD_%s ""' % n, '#define HKN_%s 0' % n, '#endif']
    out.append('')
    out.append('#define HAKIOS_DRIVERS_TOTAL %d' % len(names))
    out.append('#define HAKIOS_DRIVERS_BUILT ""' + ''.join(' HKD_%s' % n for n in names))
    out.append('#define HAKIOS_DRIVERS_COUNT (0' + ''.join(' + HKN_%s' % n for n in names) + ')')
    out += ['', '#endif', '']
    return '\n'.join(out)


def master_options_block(drivers):
    lines = [OPT_BEGIN]
    for n in sorted(drivers):
        lines.append('options\t\tHAKIOS_%s\t# %s driver (config/hakios/%s.drivers)\t# <%s>' % (n, n, drivers[n].sub, drivers[n].attr))
    lines.append(OPT_END)
    return '\n'.join(lines)


def group_line(on):
    return '#  HAKIOS_DRIVERS = [ %s ]' % ' '.join('hakios_' + n.lower() for n in sorted(on))


def sync(xnu, drivers, standard):
    changed = []
    lines = read_files_lines(xnu)
    want = expected(drivers, standard)
    edits = {}
    for path, (cond, where) in want.items():
        if path not in lines:
            raise SystemExit('%s: %s has no line in any conf/files: add it once by hand (the tool rewrites, never invents)' % (where, path))
        f, i, words = lines[path]
        if words != cond:
            edits.setdefault(f, []).append((i, path, cond))
    for f, es in edits.items():
        p = os.path.join(xnu, f)
        text = open(p, encoding='utf-8').read().split('\n')
        for i, path, cond in es:
            text[i] = '%s\t%s' % (path.ljust(48), ' '.join(cond))
        open(p, 'w', encoding='utf-8').write('\n'.join(text))
        changed.append(f)
    # MASTER options
    p = os.path.join(xnu, MASTER)
    text = open(p, encoding='utf-8').read()
    block = master_options_block(drivers)
    if OPT_BEGIN in text:
        new = re.sub(re.escape(OPT_BEGIN) + r'.*?' + re.escape(OPT_END), lambda m: block, text, flags=re.S)
    else:
        new = text.rstrip('\n') + '\n\n' + block + '\n'
    if new != text:
        open(p, 'w', encoding='utf-8').write(new)
        changed.append(MASTER)
    # the configuration group must exist and be in every kernel configuration
    p = os.path.join(xnu, MASTER_CPU)
    text = open(p, encoding='utf-8').read()
    new = text
    if not GROUP.search(new):
        new = re.sub(r'^(#  BASE =.*)$', lambda m: group_line(set(drivers)) + '\n' + m.group(1), new, count=1, flags=re.M)
    for c in CONFIGS:
        new = re.sub(r'^(#  %s =\s*\[ BASE )(?!HAKIOS_DRIVERS )' % c, r'\1HAKIOS_DRIVERS ', new, count=1, flags=re.M)
    if new != text:
        open(p, 'w', encoding='utf-8').write(new)
        changed.append(MASTER_CPU)
    p = os.path.join(xnu, HEADER)
    h = header_text(drivers)
    if not os.path.isfile(p) or open(p, encoding='utf-8').read() != h:
        open(p, 'w', encoding='utf-8').write(h)
        changed.append(HEADER)
    return changed


def apply(xnu, on):
    p = os.path.join(xnu, MASTER_CPU)
    text = open(p, encoding='utf-8').read()
    if not GROUP.search(text):
        raise SystemExit('%s has no HAKIOS_DRIVERS line: run `sync` first' % MASTER_CPU)
    new = GROUP.sub(lambda m: group_line(on), text, count=1)
    if new != text:
        open(p, 'w', encoding='utf-8').write(new)
        return True
    return False


def tree_on(xnu):
    m = GROUP.search(open(os.path.join(xnu, MASTER_CPU), encoding='utf-8').read())
    if not m:
        return None
    inner = m.group(0).split('[', 1)[1].rsplit(']', 1)[0].split()
    return {w[len('hakios_'):].upper() for w in inner}


def check(xnu, drivers, standard, config_path=None):
    problems = []
    lines = read_files_lines(xnu)
    want = expected(drivers, standard)
    named = {}
    for path, opts, where in standard:
        named.setdefault(path, []).append(where)
    for d in drivers.values():
        for path, opts, where in d.files:
            named.setdefault(path, []).append(where)
    for path, wheres in named.items():
        if len(wheres) > 1:
            problems.append('%s is named %d times: %s' % (path, len(wheres), ', '.join(wheres)))
        if not os.path.isfile(os.path.join(xnu, path)):
            problems.append('%s: %s does not exist' % (wheres[0], path))
        if path not in lines:
            problems.append('%s: %s is in no conf/files: it would never be compiled' % (wheres[0], path))
        elif lines[path][2] != want[path][0]:
            problems.append('%s:%d: %s says `%s`, config/hakios wants `%s` (run sync)' % (
                lines[path][0], lines[path][1] + 1, path, ' '.join(lines[path][2]), ' '.join(want[path][0])))
    for path, (f, i, words) in lines.items():
        if PORT_FILE.match(path) and path not in named:
            problems.append('%s:%d: %s is a port file no config/hakios block names' % (f, i + 1, path))
        if path not in named and any(w.startswith('hakios_') for w in words):
            problems.append('%s:%d: %s is optional on a hakios_ attribute but no block names it' % (f, i + 1, path))
    master = open(os.path.join(xnu, MASTER), encoding='utf-8').read()
    if master_options_block(drivers) not in master:
        problems.append('%s: the hakios options block is missing or stale (run sync)' % MASTER)
    cpu = open(os.path.join(xnu, MASTER_CPU), encoding='utf-8').read()
    for c in CONFIGS:
        if not re.search(r'^#  %s =\s*\[ BASE HAKIOS_DRIVERS ' % c, cpu, re.M):
            problems.append('%s: configuration %s does not include HAKIOS_DRIVERS' % (MASTER_CPU, c))
    on = tree_on(xnu)
    if on is None:
        problems.append('%s: no HAKIOS_DRIVERS line' % MASTER_CPU)
    else:
        for n in sorted(on - set(drivers)):
            problems.append('%s: HAKIOS_DRIVERS names %s, which no block declares' % (MASTER_CPU, n))
        for n in sorted(on & set(drivers)):
            for r in drivers[n].requires:
                if r not in on:
                    problems.append('%s: HAKIOS_DRIVERS has %s without %s, which it requires' % (MASTER_CPU, n, r))
    hp = os.path.join(xnu, HEADER)
    if not os.path.isfile(hp) or open(hp, encoding='utf-8').read() != header_text(drivers):
        problems.append('%s is missing or stale (run sync)' % HEADER)
    if config_path:
        want_on, cp = resolve(drivers, config_path)
        problems += cp
        if on is not None and on != want_on:
            problems.append('%s builds %s; %s wants %s (run apply)' % (
                MASTER_CPU, ' '.join(sorted(on)) or '-', config_path, ' '.join(sorted(want_on)) or '-'))
    return problems


# ---- boot line against the configuration --------------------------------------------------------------------------

def load_bootargs():
    here = os.path.dirname(os.path.abspath(__file__))
    for p in (os.path.join(here, 'hk_bootargs.py'),
              os.path.join(here, '..', 'research', 'ios26-farm-r1', 'tools', 'hk_bootargs.py'),
              '/data/work/hk-farm/bin/hk_bootargs.py'):
        if os.path.isfile(p):
            spec = importlib.util.spec_from_file_location('hk_bootargs', p)
            mod = importlib.util.module_from_spec(spec)
            spec.loader.exec_module(mod)
            return mod, p
    raise SystemExit('hk_bootargs.py (HakiOS lift 5) not found beside this tool, in research/ios26-farm-r1/tools or the farm')


def owners(xnu, drivers, standard):
    """{compiled path: driver NAME or None (standard)}, and a resolver for a non-compiled reader (.h/.inc/included .c)."""
    own = {p: None for p, _, _ in standard}
    for d in drivers.values():
        for p, _, _ in d.files:
            own[p] = d.name
    cache = {}

    def of(path):
        if path in own:
            return {own[path]}
        if path in cache:
            return cache[path]
        base = os.path.basename(path)
        found = set()
        inc = re.compile(r'#\s*include\s+["<]([^">]*/)?%s[">]' % re.escape(base))
        for p, d in own.items():
            try:
                if inc.search(open(os.path.join(xnu, p), errors='replace').read()):
                    found.add(d)
            except OSError:
                pass
        cache[path] = found or {'(kernel)'}
        return cache[path]
    return of


def bootline(xnu, drivers, standard, on, line, extra):
    ba, where = load_bootargs()
    cat = ba.scan(xnu, everything=True) if 'everything' in ba.scan.__code__.co_varnames else ba.scan(xnu)
    of = owners(xnu, drivers, standard)
    problems = []
    compiled = [p for p, _, _ in standard] + [p for d in drivers.values() for p, _, _ in d.files]
    texts = {}
    tokens = (line or '').split() + (extra or '').split()
    for tok in tokens:
        name = tok.lstrip('-').split('=', 1)[0]
        if not ba.PORT.match(name) or name not in cat:
            continue
        readers = cat[name]['files']
        # a file that only names the argument in a table it hands to PE_parse_boot_argn (osfmk/arm64/blazer_pw.c's hk_pw
        # fields) forwards it for the real reader: it does not count while a direct reader exists
        direct = re.compile(r'(PE_parse_boot_arg\w*|TUNABLE\w*)\([^;]*"%s"' % re.escape(name))
        d_readers = [r for r in readers if direct.search(open(os.path.join(xnu, r), errors='replace').read())] \
            if not os.path.isfile(xnu) else readers
        # and the real readers behind a forwarder: blazer_pw_arg("blazer_thermal", ...) in a driver's own file
        via = re.compile(r'\b\w*_arg\w*\(\s*"%s"' % re.escape(name))
        for p in compiled:
            if p not in d_readers and via.search(texts.setdefault(p, open(os.path.join(xnu, p), errors='replace').read())):
                d_readers.append(p)
        readers = d_readers or readers
        drv = set()
        for r in readers:
            drv |= of(r)
        if any(d is None or d == '(kernel)' or d in on for d in drv):
            continue
        problems.append('%s is read only by %s, of %s, which this configuration leaves out' % (
            name, ', '.join(sorted(readers)), ', '.join('CONFIG_HAKIOS_' + d for d in sorted(drv))))
    return problems, where


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--xnu')
    ap.add_argument('cmd', choices=('list', 'help', 'sync', 'apply', 'show', 'check', 'bootline'))
    ap.add_argument('arg', nargs='?')
    ap.add_argument('--line')
    ap.add_argument('--extra')
    a = ap.parse_args()
    xnu = xnu_dir(a.xnu)
    drivers, standard, problems = parse(xnu)
    if problems:
        print('\n'.join(problems))
        return 1
    if a.cmd == 'list':
        for n in sorted(drivers, key=lambda n: (drivers[n].sub, n)):
            d = drivers[n]
            print('%-10s %-13s ladder %-2s req %-12s gate %-40s %s' % (
                d.sub, n, d.ladder if d.ladder is not None else '-', ','.join(d.requires) or '-',
                ','.join(d.gates) or '-', ' '.join(os.path.basename(p) for p, _, _ in d.files)))
        print('%d drivers, %d standard files' % (len(drivers), len(standard)))
        return 0
    if a.cmd == 'help':
        d = drivers.get((a.arg or '').upper().replace('CONFIG_HAKIOS_', '').replace('HAKIOS_', ''))
        if not d:
            print('no such driver'); return 1
        print('CONFIG_HAKIOS_%s (%s, %s)\n  files: %s\n  requires: %s\n  required by: %s\n  gates: %s\n  ladder: %s\n  %s' % (
            d.name, d.sub, d.line, ' '.join(p for p, _, _ in d.files), ' '.join(d.requires) or '-',
            ' '.join(n for n, o in drivers.items() if d.name in o.requires) or '-', ' '.join(d.gates) or '-',
            d.ladder, '\n  '.join(d.help)))
        return 0
    if a.cmd == 'sync':
        ch = sync(xnu, drivers, standard)
        print('sync: %s' % (', '.join(ch) if ch else 'nothing to change'))
        return 0
    if a.cmd in ('apply', 'show', 'bootline'):
        if not a.arg:
            ap.error('%s needs CONFIG' % a.cmd)
        on, problems = resolve(drivers, a.arg)
        if problems:
            print('\n'.join(problems))
            return 1
        if a.cmd == 'show':
            print('%d drivers built in (%s), %d left out (%s)' % (
                len(on), ' '.join(sorted(on)), len(drivers) - len(on), ' '.join(sorted(set(drivers) - on))))
            return 0
        if a.cmd == 'apply':
            print('apply: %s %s' % (MASTER_CPU, 'changed' if apply(xnu, on) else 'already so'))
            print(group_line(on))
            return 0
        problems, where = bootline(xnu, drivers, standard, on, a.line, a.extra)
        print('\n'.join(problems) if problems else 'bootline OK against %s (%d drivers; catalogue %s)' % (a.arg, len(on), where))
        return 1 if problems else 0
    problems = check(xnu, drivers, standard, a.arg)
    print('\n'.join(problems) if problems else 'check OK: %d drivers, %d standard files, tree builds %s' % (
        len(drivers), len(standard), ' '.join(sorted(tree_on(xnu) or [])) or '-'))
    return 1 if problems else 0


if __name__ == '__main__':
    sys.exit(main())
