#!/usr/bin/env python3
"""Generate shim/menu_assets.h: 8-bit alpha masks for the startup menu.

  python3 shim/gen_menu_assets.py FONT_DIR > shim/menu_assets.h

FONT_DIR holds Inter-SemiBold.ttf, Inter-Medium.ttf and Inter-Regular.ttf (Inter,
SIL Open Font License 1.1, https://rsms.me/inter). Text is pre-rendered per string
so kerning and anti-aliasing are exact; the icons are original drawings rendered
at 4x and downsampled. No Apple or Google artwork is used."""
import sys
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

D = Path(sys.argv[1])
SS = 4  # icon supersampling


def font(weight, size):
    return ImageFont.truetype(str(D / f'Inter-{weight}.ttf'), size)


def text_mask(s, weight, size, tracking=0):
    f = font(weight, size)
    asc, desc = f.getmetrics()
    w = int(f.getlength(s) + tracking * max(0, len(s) - 1)) + 8
    im = Image.new('L', (w, asc + desc + 8), 0)
    d = ImageDraw.Draw(im)
    if tracking:
        x = 4
        for ch in s:
            d.text((x, 4), ch, font=f, fill=255)
            x += f.getlength(ch) + tracking
    else:
        d.text((4, 4), s, font=f, fill=255)
    box = im.getbbox()
    im = im.crop((0, box[1], w, box[3]))
    # trim horizontally but keep the pen origin at x=4 for advance math
    l, r = im.getbbox()[0], im.getbbox()[2]
    im = im.crop((l, 0, r, im.height))
    return im, dict(baseline=4 + asc - box[1], advance=int(round(f.getlength(s))), left=l - 4)


def icon_ios(n):
    c = n * SS
    im = Image.new('L', (c, c), 0); d = ImageDraw.Draw(im)
    bw, bh = int(c * 0.46), int(c * 0.90)
    x0, y0 = (c - bw) // 2, (c - bh) // 2
    st = int(c * 0.030)
    d.rounded_rectangle((x0, y0, x0 + bw, y0 + bh), radius=int(c * 0.10), outline=255, width=st)
    cols, rows = 4, 5
    inner = bw - 2 * int(bw * 0.15)
    gap = int(inner * 0.085)
    cell = (inner - (cols - 1) * gap) // cols
    gx = x0 + (bw - (cols * cell + (cols - 1) * gap)) // 2
    gy = y0 + int(bh * 0.13)
    for r in range(rows):
        for k in range(cols):
            ax, ay = gx + k * (cell + gap), gy + r * (cell + gap)
            d.rounded_rectangle((ax, ay, ax + cell, ay + cell), radius=int(cell * 0.28), fill=255)
    dy = y0 + bh - int(bh * 0.20)
    for k in range(cols):   # dock: the same icons, a little dimmer
        ax = gx + k * (cell + gap)
        d.rounded_rectangle((ax, dy, ax + cell, dy + cell), radius=int(cell * 0.28), fill=150)
    hw = int(bw * 0.30); hy = y0 + bh - int(bh * 0.05)
    d.rounded_rectangle(((c - hw) // 2, hy - st // 2, (c + hw) // 2, hy + st // 2), radius=st // 2, fill=255)
    return im.resize((n, n), Image.LANCZOS)


def icon_android(n):
    c = n * SS
    im = Image.new('L', (c, c), 0); d = ImageDraw.Draw(im)
    hw = int(c * 0.74); hx0 = (c - hw) // 2; hy = int(c * 0.70)   # head: upper half-disc
    d.pieslice((hx0, hy - hw // 2, hx0 + hw, hy + hw // 2), 180, 360, fill=255)
    st = int(c * 0.034)
    for sx in (-1, 1):   # antennae
        bx = c // 2 + sx * int(hw * 0.24); by = hy - int(hw * 0.40)
        tx = c // 2 + sx * int(hw * 0.35); ty = hy - int(hw * 0.60)
        d.line((bx, by, tx, ty), fill=255, width=st)
        d.ellipse((tx - st // 2, ty - st // 2, tx + st // 2, ty + st // 2), fill=255)
    er = int(c * 0.034)
    for sx in (-1, 1):   # eyes, cut out
        ex = c // 2 + sx * int(hw * 0.21); ey = hy - int(hw * 0.19)
        d.ellipse((ex - er, ey - er, ex + er, ey + er), fill=0)
    return im.resize((n, n), Image.LANCZOS)


ASSETS = []


def add(name, im, meta=None):
    ASSETS.append((name, im, meta or dict(baseline=0, advance=im.width, left=0)))


add('label_android', *text_mask('Android', 'SemiBold', 58))
add('label_ios', *text_mask('iOS', 'SemiBold', 58))
add('count_android', *text_mask('Starting Android in', 'Medium', 36))
add('count_ios', *text_mask('Starting iOS in', 'Medium', 36))
for k in range(10):
    add(f'digit_{k}', *text_mask(str(k), 'Medium', 36))
add('hint', *text_mask('Use the volume keys to choose', 'Regular', 33))
add('no_ios', *text_mask('Not installed yet', 'Regular', 30))
add('title', *text_mask('Choose a startup system', 'Medium', 40))
add('icon_ios', icon_ios(220))
add('icon_android', icon_android(220))

out = ['/* Generated by shim/gen_menu_assets.py from Inter (SIL OFL 1.1) and original icon',
       ' * drawings. Do not edit. 8-bit alpha masks, row-major, one blob + offsets',
       ' * (the shim image may carry no absolute relocations). */',
       '#pragma once', '#include <stdint.h>',
       'struct tgl_menu_mask { uint16_t w, h; int16_t baseline, advance, left; uint32_t off; };']
blob = b''; offs = []
for name, im, m in ASSETS:
    offs.append(len(blob)); blob += im.tobytes()
out.append(f'static const uint8_t menu_blob[{len(blob)}] = {{')
for i in range(0, len(blob), 40):
    out.append('\t' + ','.join(str(b) for b in blob[i:i + 40]) + ',')
out.append('};')
out.append('enum {')
for i, (name, _, _) in enumerate(ASSETS):
    out.append(f'\tMENU_{name.upper()} = {i},')
out.append(f'\tMENU_ASSET_COUNT = {len(ASSETS)}')
out.append('};')
out.append('static const struct tgl_menu_mask menu_assets[MENU_ASSET_COUNT] = {')
for (name, im, m), o in zip(ASSETS, offs):
    out.append(f"\t{{ {im.width}, {im.height}, {m['baseline']}, {m['advance']}, {m['left']}, {o}u }},")
out.append('};')
print('\n'.join(out))
