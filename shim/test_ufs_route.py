#!/usr/bin/env python3
"""Host test of the UFS route. Generates out/ufs_replay.h from the phone's decoded record, builds the real engines
against a fake controller under sanitizers, and checks the wire, the record, the gates and mutants. Exit 0 only if all
hold. No device access. UFS_REPLAY_JSON overrides the record; the record is a local capture, not in git."""
import json, os, pathlib, re, shutil, struct, subprocess, sys, zlib
S = pathlib.Path(__file__).resolve().parent; OUT = S/'out'/'ufs_test'; OUT.mkdir(parents=True, exist_ok=True)
ROOT = S.parent
D = pathlib.Path(os.environ.get('UFS_REPLAY_JSON', ROOT/'research/ufs-read-r2/run/decoded.json'))
if not D.exists(): sys.exit(f'test_ufs_route: phone record missing: {D}')
d = json.loads(D.read_text()); fails = []; checks = 0
LINK = json.loads((ROOT/'research/ufs-link-r2/decoded.json').read_text())['pass_b']
def ok(c, what):
    global checks; checks += 1
    if not c: fails.append(what); print('FAIL', what)
def carr(b): return '{' + ','.join(str(x) for x in b) + '}'
# Real bytes. A block is real if its CRC reproduces what the phone recorded for it.
hdr = {h['lun']: bytes.fromhex(h['raw']) + bytes(4096 - 92) for h in d['headers']}
crc_rec = {(r['lun'], r['lba']): r['crc32'] for r in d['reads']}
for lun, b in hdr.items(): ok(zlib.crc32(b) == crc_rec[(lun, 1)], f'header LU{lun} is the real whole block')
ok(zlib.crc32(bytes(4096)) == 3340501009, 'recorded zero-block CRC')
def fixed_gpt(lun, lu):
    """SYNTHETIC entry arrays carrying the phone's real rows; the real arrays were not recorded. The header is then
    re-sealed for them, everything else in it unchanged."""
    n = lu['num_entries']; rows = {p['index']: p for p in d['partitions'] if p['lun'] == lun}
    a = bytearray(n * 128); fu = struct.unpack_from('<Q', hdr[lun], 40)[0]
    for i in range(n):
        e = bytearray(128); e[0] = 0xa5; e[16] = i + 1; p = rows.get(i)
        first, last, name = (p['first_lba'], p['last_lba'], p['name']) if p else (fu, fu, f'row{i}')
        struct.pack_into('<QQ', e, 32, first, last); e[56:56 + 2 * len(name)] = name.encode('utf-16-le'); a[i * 128:(i + 1) * 128] = e
    h = bytearray(hdr[lun]); struct.pack_into('<I', h, 88, zlib.crc32(bytes(a))); struct.pack_into('<I', h, 16, 0)
    struct.pack_into('<I', h, 16, zlib.crc32(bytes(h[:92])))
    return bytes(h), bytes(a)
blocks = []
for lu in d['lus']:
    lun = lu['lun']; h, a = fixed_gpt(lun, lu)
    blocks.append((lun, 1, hdr[lun], h))
    for i in range(0, len(a), 4096):
        b = a[i:i + 4096].ljust(4096, b'\0'); blocks.append((lun, lu['entry_lba'] + i // 4096, b, b))
for r in d['reads']:
    if r['step'] != 'TARGET': continue
    # Real where the phone's CRC is the zero block's; otherwise the 64 recorded bytes, zero after. Labelled, not real.
    b = bytes(4096) if r['crc32'] == 3340501009 else bytes.fromhex(r['head']).ljust(4096, b'\0')
    blocks.append((r['lun'], r['lba'], b, b))
H = [f'/* GENERATED by test_ufs_route.py from {D.name}. Do not commit: derived from a device capture. */', '#include <stdint.h>']
cmds = d['commands']
H += [f'#define REPLAY_NCMDS {len(cmds)}u', f'#define REPLAY_NLUS {len(d["lus"])}u', f'#define REPLAY_NREADS {len(d["reads"])}u', f'#define REPLAY_NBLOCKS {len(blocks)}u',
      f'#define REPLAY_CAP {d["preflight"]["cap"]}u', f'#define REPLAY_BUSTHRTL {d["preflight"]["busthrtl"]}u']
good = next(bytes.fromhex(c['rsp']) for c in cmds if c['step'] == 'LU_TUR' and c['fields']['status'] == 0)
H.append(f'static const uint8_t REPLAY_GOOD[32] = {carr(good[:32])};')
H.append(f'static const uint8_t REPLAY_RL[{len(d["report_luns"]["raw"]) // 2}] = {carr(bytes.fromhex(d["report_luns"]["raw"]))};')
H.append('static const struct { uint8_t req[32]; uint8_t rsp[320]; unsigned rsp_len; } replay_cmds[] = {')
for c in cmds:
    rq, rs = bytes.fromhex(c['req']), bytes.fromhex(c['rsp'])
    H.append(f' {{{carr(rq)},{carr(rs)},{len(rs)}}},')
H.append('};\nstatic const struct { unsigned lun, max_lba, block_bytes; } replay_lus[] = {')
H += [f' {{{l["lun"]},{l["max_lba"]},{l["block_bytes"]}}},' for l in d['lus']]
H.append('};\nstatic const struct { unsigned lun, lba; } replay_reads[] = {')
H += [f' {{{r["lun"]},{r["lba"]}}},' for r in d['reads']]
H.append('};')
for i, (l, a, real, fixed) in enumerate(blocks):
    H.append(f'static const uint8_t B{i}r[4096] = {carr(real)};')
    H.append(f'static const uint8_t B{i}f[4096] = {carr(fixed)};')
H.append('static const struct { unsigned lun, lba; const uint8_t *real, *fixed; } replay_blocks[] = {')
H += [f' {{{l},{a},B{i}r,B{i}f}},' for i, (l, a, _, _) in enumerate(blocks)]
H.append('};')
(OUT/'ufs_replay.h').write_text('\n'.join(H) + '\n')
CC = os.environ.get('HOSTCC_UFS', 'cc')
BASE = [CC, '-std=gnu11', '-O1', '-g', '-fsanitize=address,undefined', '-fno-sanitize-recover=undefined', '-Wall', '-Wextra', '-Wno-unused-function', '-Wno-unused-parameter', f'-I{OUT}', f'-I{S}']
def build(name, *flags, src=None):
    e = OUT/name
    srcs = [str(src)] if src else [str(S/x) for x in ('tgl_ufs_route_test.c', 'tgl_ufs_link.c', 'tgl_ufs_host.c', 'tgl_ufs_handoff.c')]
    p = subprocess.run(BASE + list(flags) + srcs + ['-o', str(e)], capture_output=True, text=True)
    if p.returncode: print(p.stderr[-3000:]); sys.exit(f'build {name} failed')
    return e
def run(e, sc):
    r = OUT/f'{e.name}.{sc}.rec'; l = OUT/f'{e.name}.{sc}.link'
    p = subprocess.run([str(e), sc, str(r), str(l)], capture_output=True, text=True, timeout=120)
    return p, p.stdout
def field(out, key, line='R'):
    m = re.search(rf'^{line} .*\b{key}=(-?\w+)', out, re.M); return m.group(1) if m else None
main = build('t')
# 1. Whole route: link trace, then the phone's frames in the phone's order.
p, o = run(main, 'replay'); ok(p.returncode == 0, 'replay no violations: ' + (o[-400:] if p.returncode else ''))
e = d['end']
want = dict(rc='0', phase='11', dma='1', quar='0', stopped='1', flag_reads=str(e['flag_reads']), tur=str(e['tur_attempts']), ua=str(e['ua_seen']), list=str(e['list_len']), luns=str(e['lun_count']),
            reads=str(e['read_blocks']), found='1', tlun=str(e['target_lun']), first=str(e['target_first']), last=str(e['target_last']), real_at=f'{len(cmds)}', read_at=str(len(d['reads'])))
for k, v in want.items(): ok(field(o, k) == v, f'replay {k}: {field(o, k)} want {v}')
ok(field(o, 'rc', 'L') == '0' and field(o, 'attempts', 'L') == '1' and field(o, 'up', 'L') == '1', 'link result 0 on the first LINK')
ok(LINK['link']['attempts'] == 1 and LINK['link']['results'] == [0], 'phone pass B linked first try')
tr = re.findall(r'^T (.*)$', o, re.M)
golden = ['PAD 2 4 2', 'PAD 2 8 8',            # refclk pad: mux; TX write that does not stick
          'PAD 0 4 1', 'PAD 0 0 1101',          # reset pad: mux, PARAM. TX already OE, DOUT 0: low
          'PAD 1 4 1',                          # power pad: mux to output; its latch already holds OE|DOUT
          'SMC 3', 'PAD 0 8 c', 'SMC 16',       # refclk, reset high, aux
          'HCE 0', 'HCE 3']                     # HCE cycle keeps crypto
dl = LINK['pads_pre_write']
ok((dl['reset_pad0']['param'], dl['reset_pad0']['dmux'], dl['reset_pad0']['txdata']) == ('0x1100', '0x1', '0x8'), 'fake seeded with phone reset pad')
ok((dl['power_pad8']['param'], dl['power_pad8']['dmux'], dl['power_pad8']['txdata']) == ('0x1100', '0x0', '0xc'), 'fake seeded with phone power pad')
ok((dl['refclk_pad1']['param'], dl['refclk_pad1']['dmux'], dl['refclk_pad1']['txdata']) == ('0x1001', '0x2', '0x0'), 'fake seeded with phone refclk pad')
ok(tr[:len(golden)] == golden, f'device-on and HCE order: {tr[:len(golden)]}')
rest = tr[len(golden):]
diag = lambda: ['UIC 1 d000 0', 'UIC 1 41 0', 'UIC 1 41 0', 'UIC 1 c1 0', 'UIC 1 c1 0']
want_tail = diag() + ['HCLKDIV c8', 'TOP 200 101', 'UIC 2 8118 0', 'UIC 2 d085 1', 'UIC 16 0 0'] + diag()
# post-link UIC follows, compared below with the phone's list
ok(rest[:len(want_tail)] == want_tail, f'pre-link order: {rest[:len(want_tail)]}')
uic = rest[len(want_tail):]
OPS = {'DME_GET': 1, 'DME_SET': 2, 'DME_PEER_SET': 4, 'DME_PEER_GET': 3}
real_uic = [f"UIC {OPS[u['op']]:x} {u['attr']:x} {u['set_value']:x}" for u in d['uic']]
ok(uic == real_uic, f'post-link UIC equals the phone record ({len(real_uic)}): {uic[:3]}')
for r in re.findall(r'^Z (\d) rc=(-?\d+) gpt=(\d) crc=(\d)', o, re.M): ok(r[1:] == ('0', '1', '1'), f'LU {r[0]} table')
ok(field(o, 'outcome', 'F') == '1', 'handoff LIVE after the replay')
# 2. The record decodes with ufs-read-r2's own decoder, and matches the phone's result.
dec = subprocess.run([sys.executable, '-I', str(ROOT/'research/ufs-read-r2/decode_read.py'), str(OUT/'t.replay.rec'), 'bdf582b45d69800af51a519354958306', '0x202611012500', '--raw-record'], capture_output=True, text=True)
ok(dec.returncode == 0, 'decode_read.py accepts the record: ' + dec.stderr[-300:])
if dec.returncode == 0:
    dd = json.loads(dec.stdout)
    for k in ('rc', 'phase', 'lists_stopped', 'read_blocks', 'target_first', 'target_last', 'ua_seen', 'hcs', 'lun_count'):
        ok(dd['end'][k] == e[k], f'decoded end.{k}: {dd["end"][k]} phone {e[k]}')
    ok([(c['fields']['req_lun'], c['fields'].get('response'), c['fields'].get('status')) for c in dd['commands']] == [(c['fields']['req_lun'], c['fields'].get('response'), c['fields'].get('status')) for c in cmds], 'same logged commands, response=1 included')
    z = [r for r in dd['reads'] if r['step'] == 'TARGET']; rz = [r for r in d['reads'] if r['step'] == 'TARGET']
    ok([(r['lba'], r['crc32']) for r in z if r['crc32'] == 3340501009] == [(r['lba'], r['crc32']) for r in rz if r['crc32'] == 3340501009], 'zero blocks: CRCs equal the phone')
    ok([r['head'] for r in z] == [r['head'] for r in rz], 'target heads equal the phone')
    ok(dd['target']['first_lba'] == 2500838 and dd['target']['blocks'] == 2097152, 'target located from real rows')
# 3. Link record decodes.
dec = subprocess.run([sys.executable, '-I', str(S/'decode_ufs_boot.py'), '--link-record', str(OUT/'t.replay.link'), '0x2df5ab6e1c7d9dbe', '0x202611012500'], capture_output=True, text=True)
ok(dec.returncode == 0 and json.loads(dec.stdout)['link']['link_up'] == 1, 'decode_ufs_boot.py reads the link record: ' + dec.stderr[-300:])
# 4. Real headers, unmodified: accepted. Synthetic arrays then fail their real CRCs, so no target is taken.
p, o = run(main, 'strict_headers'); ok(p.returncode == 0, 'strict no violations: ' + o[-300:])
ok(all(g == '1' and c == '0' for _, _, g, c in re.findall(r'^Z (\d) rc=(-?\d+) gpt=(\d) crc=(\d)', o, re.M)) and field(o, 'rc') == '-22' and field(o, 'found') == '0', 'real GPT headers valid; bad array CRC yields no target')
ok(field(o, 'outcome', 'F') == '2', 'handoff DOWN without a target, lists stopped')
# 5. Refusals.
for sc, key, want_ in [('pg', 'rc', '-6'), ('decouple', 'rc', '-14'), ('bad_top', 'rc', '-5'), ('psm_off', 'rc', '-13'), ('stale_doorbell', 'rc', '-10')]:
    p, o = run(main, sc); ok(field(o, key, 'L') == want_, f'{sc}: link rc {field(o, key, "L")}')
    ok(field(o, 'dma') == '0' and field(o, 'reads') == '0', f'{sc}: no DMA')
    if sc != 'stale_doorbell': ok(not re.search(r'^T ', o, re.M), f'{sc}: no write')
    ok(field(o, 'outcome', 'F') == '0', f'{sc}: handoff NO_DMA')
p, o = run(main, 'read_timeout'); ok(field(o, 'rc') == '-10' and field(o, 'quar') == '1' and field(o, 'outcome', 'F') == '-1', 'READ timeout quarantines, handoff HALT')
p, o = run(main, 'read_short'); ok(field(o, 'quar') == '0' and field(o, 'found') == '0', 'short READ refused')
p, o = run(main, 'smmu_drift'); ok(field(o, 'rc') == '-5', 'SMMU drift stops')
p, o = run(main, 'ahit'); ok(field(o, 'outcome', 'F') == '2' and field(o, 'ahit', 'F') == '1001', 'AHIT set: DOWN')
p, o = run(main, 'fatal_is'); ok(field(o, 'outcome', 'F') == '2', 'fatal IS at handoff: DOWN')
p, o = run(main, 'bad_hdr_crc'); ok(field(o, 'rc') == '-22' and field(o, 'found') == '0' and 'gpt=1' not in o, 'GPT header CRC is checked')
# 6. Gates. Each off shows what it does.
e2 = build('g_refclk', '-DTGL_UFS_REFCLK_RELAX=0'); p, o = run(e2, 'replay'); ok(field(o, 'rc', 'L') == '-9' and 'HCE' not in o, 'refclk strict: stops at the pad, as ufs-link-r1 did')
e2 = build('g_status', '-DTGL_UFS_SCSI_STATUS_ONLY=0'); p, o = run(e2, 'replay'); ok(field(o, 'rc') == '-16' and field(o, 'tur') == '1', 'response=1 fatal: stops at first TUR, as ufs-postlink-r1 did')
e2 = build('g_read', '-DTGL_UFS_READ=0'); p, o = run(e2, 'replay'); ok(field(o, 'rc') == '0' and field(o, 'reads') == '0' and field(o, 'luns') == '4', 'read off: no storage command')
# 7. Wire gate, whole frames: only the phone's commands pass.
gt = OUT/'gate.c'; gt.write_text(r'''
#include <stdio.h>
#include <string.h>
#include "tgl_ufs_host.c"
static unsigned g_bells; static uint64_t g_t;
static int g_rd(void *c, uint32_t o, uint32_t *v) { (void)c; (void)o; *v = 0; return 0; }
static int g_wr(void *c, uint32_t o, uint32_t v) { (void)c; (void)v; if (o == R_UTRLDBR) g_bells++; return 0; }
static int g_now(void *c, uint64_t *t) { (void)c; *t = g_t++; return 0; }
static int g_delay(void *c, uint32_t a, uint32_t b) { (void)c; (void)a; (void)b; return 0; }
static int g_sync(void *c, unsigned d) { (void)c; (void)d; return 0; }
static int g_rec(void *c, uint32_t o, const uint8_t *b, uint32_t n) { (void)c; (void)o; (void)b; (void)n; return 0; }
int main(void) {
  static const unsigned allowed[][2] = {{0x00,0},{0x25,1},{0x28,1},{0xa0,1}}; unsigned bad = 0, n = 0;
  uint8_t r[32];
  for (unsigned op = 0; op < 256; op++) for (unsigned fl = 0; fl < 3; fl++) for (unsigned data = 0; data < 2; data++) for (unsigned lun = 0; lun < 256; lun += 1) {
    uint32_t alloc = op == 0x25 ? 8 : (data ? 4096 : 0);
    memset(r, 0, 32); r[0] = 1; r[1] = fl == 1 ? 0x40 : fl == 2 ? 0x20 : 0; r[2] = (uint8_t)lun; r[4] = IID_ONE;
    r[12] = (uint8_t)(alloc >> 24); r[13] = (uint8_t)(alloc >> 16); r[14] = (uint8_t)(alloc >> 8); r[15] = (uint8_t)alloc; r[16] = (uint8_t)op;
    if (op == 0x28) { r[23] = 0; r[24] = 1; } if (op == 0xa0) { r[24] = 0x10; }
    int a = wire_allowed(r, data, alloc), w = 0;
    if (op == 0x00 && !fl && !data && (lun < 8 || lun == 0x81)) w = 1;
    if (op == 0x25 && fl == 1 && data && lun < 8) w = 1;
    if (op == 0x28 && fl == 1 && data && lun < 8) w = 1;
    if (op == 0xa0 && fl == 1 && data && lun == 0x81) w = 1;
    n++; if (a != w) { printf("GATE op %02x fl %u data %u lun %u: %d\n", op, fl, data, lun, a); bad++; }
  }
  /* any write-class opcode with write flag, and one-block READ variants */
  static const uint8_t wr[] = {0x0a,0x2a,0xaa,0x8a,0x41,0x42,0x04,0x1b,0x35,0x55,0x3b,0x93};
  for (unsigned i = 0; i < sizeof wr; i++) { memset(r,0,32); r[0]=1; r[1]=0x20; r[4]=IID_ONE; r[14]=0x10; r[16]=wr[i]; n++; if (wire_allowed(r,0,4096)||wire_allowed(r,1,4096)) { printf("GATE write %02x\n", wr[i]); bad++; } }
  for (unsigned b = 17; b < 32; b++) { if (b >= 18 && b <= 21) continue; if (b == 24) continue; memset(r,0,32); r[0]=1; r[1]=0x40; r[4]=IID_ONE; r[14]=0x10; r[16]=0x28; r[24]=1; r[b]=1; n++; if (wire_allowed(r,1,4096)) { printf("GATE read byte %u\n", b); bad++; } }
  for (unsigned c = 0; c < 256; c++) { memset(r,0,32); r[0]=1; r[1]=0x40; r[4]=IID_ONE; r[14]=0x10; r[16]=0x28; r[24]=(uint8_t)c; n++; if (wire_allowed(r,1,4096) != (c == 1)) { printf("GATE count %u\n", c); bad++; } }
  /* queries: only fDeviceInit set and read */
  for (unsigned fn = 0; fn < 256; fn += 1) for (unsigned op = 0; op < 16; op++) for (unsigned idn = 0; idn < 32; idn++) {
    memset(r,0,32); r[0]=0x16; r[4]=IID_ONE; r[5]=(uint8_t)fn; r[12]=(uint8_t)op; r[13]=(uint8_t)idn;
    int w = idn == 1 && ((fn == 0x81 && op == 6) || (fn == 0x01 && op == 5)); n++;
    if (wire_allowed(r,0,0) != w) { printf("GATE query %02x %x %x\n", fn, op, idn); bad++; }
  }
  /* task management and every other transaction type */
  for (unsigned t = 0; t < 256; t++) { if (t==0||t==1||t==0x16) continue; memset(r,0,32); r[0]=(uint8_t)t; r[4]=IID_ONE; n++; if (wire_allowed(r,0,0)) { printf("GATE txn %02x\n", t); bad++; } }
  /* EDTL must equal the allocation */
  memset(r,0,32); r[0]=1; r[1]=0x40; r[4]=IID_ONE; r[13]=0x20; r[16]=0x28; r[24]=1; n++; if (wire_allowed(r,1,4096)) { puts("GATE edtl"); bad++; }
  /* The media bound holds at the doorbell, below every caller */
  { static struct st t; static struct tgl_ufsh_request q; static struct tgl_ufsh_result o; static struct tgl_ufsh_ports P; static uint8_t ar[TGL_UFSH_ARENA_BYTES];
    P.hc_rd=g_rd; P.hc_wr=g_wr; P.now_us=g_now; P.delay_us=g_delay; P.sync=g_sync; P.rec_write=g_rec; q.arena=ar; q.arena_bus=0x80004000; t.q=&q; t.p=&P; t.o=&o; t.deadline=UINT64_MAX;
    unsigned allowed_=0; for (unsigned i = 0; i < 40; i++) { memset(t.req,0,32); t.req[0]=1; t.req[1]=0x40; t.req[4]=IID_ONE; t.req[14]=0x10; t.req[16]=0x28; t.req[24]=1; ar[0x808]=0; ar[0x800+0x200]=0x21;
      int rc = exchange_(&t,1,4096,1000000,0x21); if (rc != TGL_UFSH_E_DENIED) allowed_++; }
    n++; if (allowed_ != TGL_UFSH_MAX_READ_BLOCKS || g_bells != TGL_UFSH_MAX_READ_BLOCKS) { printf("GATE bound %u bells %u\n", allowed_, g_bells); bad++; } }
  printf("gate %u frames, %u wrong\n", n, bad); return bad != 0;
}
''')
