#!/usr/bin/env python3
"""Write reserved.h for test_memplan.c from this phone's own records (local, not in git):
  research/ios26-dualboot-r8/truth/fdt.dts            memory banks, fixed-reg reserved-memory children
  research/ios26-dualboot-r8/truth/iomem.txt          Android's /proc/iomem (one boot): reserved spans
  research/ios26-dualboot-r8/attempts/final-return/dmesg.txt   where Android placed its dynamic pools
Only addresses and node names go into reserved.h.
  gen_reserved.py REPO OUT.h
"""
import re, sys
from pathlib import Path

repo, out = Path(sys.argv[1]), Path(sys.argv[2])
T = repo/'research/ios26-dualboot-r8/truth'
dts = (T/'fdt.dts').read_text().split('\n')


def cells(s):
    return [int(x, 16) for x in re.findall(r'0x[0-9a-f]+', s)]


banks = []
for i, l in enumerate(dts):
    if re.match(r'^\t(\w+: )?memory@[0-9a-f]+ \{', l):
        for l2 in dts[i + 1:i + 6]:
            m = re.match(r'\s*reg = <(.*)>;', l2)
            if m:
                v = cells(m.group(1)); banks.append(((v[0] << 32) | v[1], (v[2] << 32) | v[3])); break
banks.sort()

fixed = []
s = next(i for i, l in enumerate(dts) if 'reserved-memory {' in l)
d, cur, reg = 0, None, None
for l in dts[s:]:
    o, c = l.count('{'), l.count('}')
    if d == 1 and o:
        cur, reg = l.strip().split(' {')[0].split(': ')[-1], None
    if d == 2 and cur:
        m = re.match(r'\s*reg = <(.*)>;', l)
        if m:
            reg = cells(m.group(1))
    d += o - c
    if d == 1 and c and cur:
        if reg:
            for a in range(0, len(reg) - 3, 4):
                b, z = (reg[a] << 32) | reg[a + 1], (reg[a + 2] << 32) | reg[a + 3]
                if z:
                    fixed.append((b, b + z, cur))
        cur = None
    if d == 0 and c:
        break

iomem = []
for l in (T/'iomem.txt').read_text().split('\n'):
    m = re.match(r'^\s*([0-9a-f]+)-([0-9a-f]+) : reserved$', l)
    if m:
        iomem.append((int(m.group(1), 16), int(m.group(2), 16) + 1))

dyn = []
for l in (repo/'research/ios26-dualboot-r8/attempts/final-return/dmesg.txt').read_text(errors='replace').split('\n'):
    m = re.search(r'OF: reserved mem: 0x([0-9a-f]+)\.\.0x([0-9a-f]+) \(\d+ KiB\) (\S+) (\S+) (\S+)$', l)
    if m and not any(f[2] == m.group(5) for f in fixed):
        dyn.append((int(m.group(1), 16), int(m.group(2), 16) + 1, f'{m.group(5)} ({m.group(3)} {m.group(4)})'))

w = ['/* Generated by gen_reserved.py from fdt.dts, iomem.txt, final-return/dmesg.txt. Addresses only. */',
     'struct rr { uint64_t pa, end; const char *name; };']
w.append('static const struct rr banks[] = {')
w += [f'\t{{ 0x{b:x}ULL, 0x{b + z:x}ULL, "memory@{b:x}" }},' for b, z in banks] + ['};']
w.append('static const struct rr fixed[] = {  /* reserved-memory children with a fixed reg */')
w += [f'\t{{ 0x{a:x}ULL, 0x{b:x}ULL, "{n}" }},' for a, b, n in sorted(fixed)] + ['};']
w.append('static const struct rr iomem_reserved[] = {  /* Android /proc/iomem "reserved", one boot */')
w += [f'\t{{ 0x{a:x}ULL, 0x{b:x}ULL, "iomem" }},' for a, b in sorted(iomem)] + ['};']
w.append('static const struct rr android_dynamic[] = {  /* placed by Android at its boot (no fixed reg) */')
w += [f'\t{{ 0x{a:x}ULL, 0x{b:x}ULL, "{n}" }},' for a, b, n in sorted(dyn)] + ['};']
out.write_text('\n'.join(w) + '\n')
print(f'banks {len(banks)} ({sum(z for _, z in banks) >> 30} GiB), fixed {len(fixed)}, iomem reserved {len(iomem)}, android dynamic {len(dyn)}')
