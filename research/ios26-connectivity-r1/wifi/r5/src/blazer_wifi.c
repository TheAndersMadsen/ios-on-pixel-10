/* SPDX-License-Identifier: MIT
 * The whole of XNU's part in Wi-Fi up to one passive scan: boot args, device mappings, host memory and one thread. Everything else is blazer_pcie1.c, blazer_bcm4390.c, blazer_bcm4390_ring.c, blazer_bcm4390_scan.c and blazer_bcm4390_join.c; en0 and the secret are blazer_wifi_net.c.
 *
 * Off unless blazer_wifi=1: no thread, no mapping, no access, no host memory. With it, some seconds into the boot, the link comes up, firmware loads and runs, the radio listens once on every channel it allows, what it heard goes to the log, and the chip goes off again.
 * No network interface, no interrupts, no join, no credentials. The chip can reach only the DMA buffer below, and bus master goes off before the link does.
 *
 *   blazer_wifi=1              run. Each polled CPM frame takes cpmlock's lock, so touch and thermal can run alongside
 *   blazer_wifi_stage=0..8     how far, default 7. 0: reads only. 1: power vote and resets. 2: PHY and root port. 3: chip and link. 4: BARs, security register, backplane, OTP. 5: firmware. 6: rings and first ioctls. 7: passive scan. 8: settings, a dry run: nothing is sent. blazer_pcie1.h
 *   blazer_wifi_join=1         stage 8 only: join the network in the image. THIS TRANSMITS. Refused with no network in the image (tools/mkwifisecret.py)
 *   blazer_wifi_net=0..2       stage 8: 0 no interface. 1 en0, and the kernel's own DHCP and a ping to the gateway. 2 en0 for configd. Default 1 when joining
 *   blazer_wifi_run=N          stage 8, joined: chip goes off after N seconds, default 120. 0: for good
 *   blazer_wifi_idx_tcm=1      ring indices in the chip's RAM, DHD's fallback. Default: in host memory, Android's way
 *   blazer_wifi_flr=0..2       FLRs before the load, default 2, as Android's boot
 *   blazer_wifi_mem_atu=1      an outbound iATU region for the BARs. Stock has none
 *   blazer_wifi_gen=1..3       link speed, default 1
 *   blazer_wifi_delay=N        seconds after this call, default 30
 *   blazer_wifi_end=N          N seconds after the result, panic with it, so blazer_panic=1 ends the boot and the log can be read. Default: boot goes on
 *   blazer_wifi_hold=1         on success, leave the link up and the chip on
 *   blazer_wifi_aux=1          also send the aux clock's SIP call, which the shim's UFS route has already sent
 *   blazer_wifi_force=1        go on though the PHY or LTSSM reads as already started: a warm boot might leave it so (not seen)
 */
