static struct {
	uint64_t pa;
	uint32_t size;
	vm_offset_t va;
} windows[] = {
	{ 0x05250000ULL, 0x1000, 0 }, { 0x05272000ULL, 0x1000, 0 },     /* mailbox */
	{ 0x3c59a000ULL, 0x1000, 0 }, { 0x3c59b000ULL, 0x1000, 0 }, { 0x3c59c000ULL, 0x1000, 0 }, { 0x3c59d000ULL, 0x1000, 0 },     /* pads 0x0a..0x0d */
	{ 0x3c500000ULL, 0x1000, 0 }, { 0x3c520000ULL, 0x1000, 0 }, { 0x3c550000ULL, 0xa000, 0 },       /* sii, top, phy_sram */
	{ 0x3c800000ULL, 0x1000, 0 }, { 0x3cb00000ULL, 0x1000, 0 }, { 0x60000000ULL, 0x1000, 0 },       /* dbi, atu, first page of config */
	{ 0x60800000ULL, 0x10000, 0 }, { 0x60400000ULL, 0x400000, 0 },  /* the endpoint's BAR 0 and BAR 2, where blazer_bcm4390.c assigns them */
};
